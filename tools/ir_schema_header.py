#!/usr/bin/env python3
"""Vendors paperkiln's IR JSON Schema (spec/ir.schema.json, IR_SPEC.md section 10.2) into graph_ir_schema.h,
the copy graph_ir_validate.cpp evaluates at load (IR_SPEC section 10.1 rule 1).

    python tools/ir_schema_header.py [SCHEMA]            # write graph_ir_schema.h beside this repo's sources
    python tools/ir_schema_header.py --check [SCHEMA]    # exit 1 unless the header holds SCHEMA's document

SCHEMA defaults to ../microtorch/spec/ir.schema.json (the workspace's paperkiln checkout). The header holds
the schema as compact JSON (the same document: --check compares the parsed objects) in raw-string pieces of at
most 4000 bytes each (MSVC caps one literal near 16 KB), and the source file's sha256.
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
HEADER = os.path.join(REPO, "graph_ir_schema.h")
DEFAULT = os.path.join(os.path.dirname(REPO), "microtorch", "spec", "ir.schema.json")
DELIM = "IRS"
PIECE = 4000


def render(raw):
    doc = json.loads(raw)
    text = json.dumps(doc, separators=(",", ":"), ensure_ascii=True)
    assert ")" + DELIM + '"' not in text
    pieces = [text[i:i + PIECE] for i in range(0, len(text), PIECE)]
    sha = hashlib.sha256(raw).hexdigest()
    lines = [
        "#pragma once",
        "// paperkiln's IR JSON Schema (spec/ir.schema.json; IR_SPEC.md section 10.2), vendored for",
        "// graph_ir_validate.cpp (section 10.1 rule 1). Generated by tools/ir_schema_header.py; do not edit:",
        "// regenerate from paperkiln's file, and --check that the copy is current.",
        f"// Source sha256: {sha}",
        "namespace ember_ir {",
        "inline const char* const kIrSchemaPieces[] = {",
    ]
    lines += [f'    R"{DELIM}({p}){DELIM}",' for p in pieces]
    lines += ["};", "}  // namespace ember_ir", ""]
    return "\n".join(lines), doc


def embedded(header_text):
    out = []
    for ln in header_text.splitlines():
        ln = ln.strip()
        if ln.startswith(f'R"{DELIM}('):
            out.append(ln[len(f'R"{DELIM}('):-len(f'){DELIM}",')])
    return json.loads("".join(out))


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if not a.startswith("--")]
    src = args[0] if args else DEFAULT
    raw = open(src, "rb").read()
    text, doc = render(raw)
    if check:
        ok = os.path.exists(HEADER) and embedded(open(HEADER, encoding="utf-8").read()) == doc
        print(("current: " if ok else "STALE: ") + f"{HEADER} against {src} (sha256 {hashlib.sha256(raw).hexdigest()})")
        return 0 if ok else 1
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {HEADER} from {src}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
